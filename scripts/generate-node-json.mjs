/**
 * Emit a specialized `exportJSON` for the core node classes, from the same
 * `json` schema those classes declare.
 *
 * The schema-driven `exportJSON` walks a compiled table per node: a loop, an
 * indirect call per property, and a keyed store whose key changes every
 * iteration. Everything it decides — which accessor to read, what the node's
 * type string is, which properties the legacy form writes — is fixed once the
 * schema is written, so it can be decided here instead and emitted as an object
 * literal. That is what the hand-written methods this schema replaced used to
 * be, recovered without hand-writing them.
 *
 * Reading a schema needs no editor and constructs no node: `$config()` is a
 * plain method on the prototype, so this runs as an ordinary build step.
 *
 * Run with `pnpm run generate-node-json`; `LexicalGeneratedJSON.test.ts` fails
 * if the checked-in output is stale or disagrees with the schema-driven path.
 */

import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

const OUT = join(
  import.meta.dirname,
  '..',
  'packages',
  'lexical',
  'src',
  'LexicalGeneratedJSON.ts',
);

const HEADER = `/**
 * Copyright (c) Meta Platforms, Inc. and affiliates.
 *
 * This source code is licensed under the MIT license found in the
 * LICENSE file in the root directory of this source tree.
 *
 */

// @generated by scripts/generate-node-json.mjs from each class's \`json\`
// schema. Run \`pnpm run generate-node-json\` to regenerate; do not edit.

// Keys are emitted in the order the schema-driven walk writes them, so the two
// produce byte-identical JSON. That order is the schema's, not alphabetical.
/* eslint-disable sort-keys-fix/sort-keys-fix */
`;

// Two phases, because reading the schemas means importing `lexical`, and
// `lexical` imports the file this script writes. Phase one replaces that file
// with a valid do-nothing module so the import always succeeds — otherwise a
// generator run that produced broken output could never be run again to fix
// it. Phase two re-enters under tsx and writes the real thing.
if (!process.env.LEXICAL_CODEGEN_PHASE_TWO) {
  writeFileSync(
    OUT,
    `${HEADER}\ntype GeneratedExporter = (node: never) => {[key: string]: unknown};\n\n/** @internal */\nexport function getGeneratedExporter(\n  _type: string,\n): undefined | GeneratedExporter {\n  return undefined;\n}\n`,
  );
  execFileSync('npx', ['tsx', fileURLToPath(import.meta.url)], {
    cwd: join(import.meta.dirname, '..'),
    env: {...process.env, LEXICAL_CODEGEN_PHASE_TWO: '1'},
    stdio: 'inherit',
  });
  process.exit(0);
}

const {
  getComposedSchemaFields,
  isSchemaField,
  LineBreakNode,
  ParagraphNode,
  TabNode,
  TextNode,
} = await import('../packages/lexical/src/index.ts');

/** Where each target class lives, for the generated file's imports. */
const MODULES = {
  LineBreakNode: 'LexicalLineBreakNode',
  ParagraphNode: 'LexicalParagraphNode',
  TabNode: 'LexicalTabNode',
  TextNode: 'LexicalTextNode',
};

/** The concrete core classes hot enough to be worth specializing. */
const TARGETS = [TextNode, ParagraphNode, LineBreakNode, TabNode];

/** `foo` → `getFoo`, matching the schema's conventional accessor name. */
function defaultGetterName(key) {
  return `get${key.charAt(0).toUpperCase()}${key.slice(1)}`;
}

/** Lookup tables the generated module needs, by the const name given to each. */
const decodeTables = new Map();

/** The expression that reads one property off `node`. */
function readExpression(klass, schema, key) {
  const {getter} = schema;
  if (getter === null) {
    return null;
  }
  if (isSchemaField(getter)) {
    if (getter.decode === undefined) {
      return `node.${getter.field}`;
    }
    // The table is plain data, so it is inlined rather than imported: keeping
    // this module free of runtime imports is what keeps it out of the cycle.
    const name = `${klass.name.replace(/Node$/, '').toUpperCase()}_${key.toUpperCase()}`;
    decodeTables.set(name, getter.decode);
    return `${name}[node.${getter.field}]`;
  }
  return `node.${getter === undefined ? defaultGetterName(key) : getter}()`;
}

function generateExport(klass) {
  const type = klass.getType();
  const fields = getComposedSchemaFields(klass);
  const reads = [];
  for (const [key, schema] of Object.entries(fields)) {
    const expression = readExpression(klass, schema, key);
    if (expression !== null) {
      reads.push({expression, key});
    }
  }
  const locals = reads
    .map(({expression, key}) => `  const ${key} = ${expression};`)
    .join('\n');
  // Every property is read before anything is written, so the fast path can be
  // a single literal. A getter may still return undefined — the walk omits the
  // property then — so the literal is taken only when none of them did.
  const defined = reads
    .map(({key}) => `${key} !== undefined`)
    .join(' &&\n    ');
  // ElementNode seeds `children` before its schema fields, so the literal has
  // to as well: the key order below is byte-identical to the walk's.
  const isElement =
    ParagraphNode.prototype instanceof Object && isElementish(klass);
  const literalEntries = [
    ...(isElement ? ['children: []'] : []),
    ...reads.map(({key}) => key),
    `type: '${type}'`,
    'version: 1',
  ];
  const incrementalEntries = reads
    .map(
      ({key}) =>
        `  if (${key} !== undefined) {\n    json.${key} = ${key};\n  }`,
    )
    .join('\n');
  if (reads.length === 0) {
    // Nothing to read, so the literal is the whole function.
    return `/** Generated from ${klass.name}'s \`json\` schema. Do not edit by hand. */
function export${klass.name}(): {[key: string]: unknown} {
  return {
    ${literalEntries.join(',\n    ')},
  };
}`;
  }
  return `/** Generated from ${klass.name}'s \`json\` schema. Do not edit by hand. */
function export${klass.name}(node: ${klass.name}): {[key: string]: unknown} {
${locals}
  if (
    ${defined}
  ) {
    return {
      ${literalEntries.join(',\n      ')},
    };
  }
  const json: {[key: string]: unknown} = ${isElement ? '{children: []}' : '{}'};
${incrementalEntries}
  json.type = '${type}';
  json.version = 1;
  return json;
}`;
}

function isElementish(klass) {
  let proto = klass;
  while (proto) {
    if (proto.name === 'ElementNode') {
      return true;
    }
    proto = Object.getPrototypeOf(proto);
  }
  return false;
}

/**
 * Whether a class's `json` schema is the whole story for its export.
 *
 * A class that overrides `exportJSON` or `exportJSONInto` does something the
 * schema does not describe — ParagraphNode back-fills `textFormat`/`textStyle`
 * from its first text child for #7971 — so a literal generated from the schema
 * alone would silently drop it.
 */
function isFullyDescribedBySchema(klass) {
  // hasOwnProperty rather than Object.hasOwn: this file is linted against the
  // browser baseline even though it only ever runs in Node.
  const has = Object.prototype.hasOwnProperty;
  return !has.call(klass.prototype, 'exportJSONInto');
}

/** Whether a class has any schema field to read, i.e. whether its generated
 * exporter takes a node at all. */
function hasFields(klass) {
  return Object.keys(getComposedSchemaFields(klass)).length > 0;
}

const generatable = TARGETS.filter(isFullyDescribedBySchema);
for (const klass of TARGETS) {
  if (!generatable.includes(klass)) {
    process.stdout.write(
      `skipping ${klass.name}: it overrides exportJSON, so its schema does not describe the whole export\n`,
    );
  }
}

const body = generatable.map(generateExport).join('\n\n');

// Emitted after the bodies, because generating them is what discovers which
// tables are needed.
const tables = [...decodeTables]
  .map(
    ([name, table]) =>
      `const ${name}: {readonly [key: string]: string} = ${JSON.stringify(table, null, 2)};`,
  )
  .join('\n\n');

writeFileSync(
  OUT,
  `${HEADER}
// Type-only, so this module has no runtime imports at all. A value import of
// the node classes would be a cycle — they import LexicalNode, which imports
// this — and would evaluate a class before its base was initialized.
${generatable
  .filter(hasFields)
  .map(k => `import type {${k.name}} from './nodes/${MODULES[k.name]}';`)
  .sort()
  .join('\n')}

${tables}${tables ? '\n\n' : ''}${body}

type GeneratedExporter = (node: never) => {[key: string]: unknown};

const EXPORTERS = new Map<string, GeneratedExporter>([
${generatable.map(k => `  ['${k.getType()}', export${k.name} as GeneratedExporter],`).join('\n')}
]);

/**
 * The generated exporter for a node type, or \`undefined\` for a type that has
 * none.
 *
 * Keyed by the type rather than by the class, which is both what keeps this
 * module free of runtime imports and what makes the lookup exact: a subclass
 * registers under its own type, so it never reaches its parent's exporter —
 * which would write the parent's type and none of the subclass's properties.
 *
 * @internal
 */
export function getGeneratedExporter(
  type: string,
): undefined | GeneratedExporter {
  return EXPORTERS.get(type);
}
`,
);

// Formatted here so the checked-in file is both prettier-clean and exactly
// what a regeneration produces — the drift check compares them byte for byte.
execFileSync('npx', ['prettier', '--write', OUT], {
  cwd: join(import.meta.dirname, '..'),
  stdio: 'pipe',
});

process.stdout.write(`wrote ${OUT}\n`);
